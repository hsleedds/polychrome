/** 평평한 목록: {id, name_ko, name_en, lat, lon, tz, country, prov_ko, prov_en, short_ko} */
export const REGIONS_KR = P.flatMap(([pk, pe, list], pi) => list.map(([k, e, lat, lon], i) => {
  const solo = pk === "세종";
  const suffix = /구$/.test(k) && pi < 8 ? "-gu" : /군$/.test(k) ? "-gun" : /시$/.test(k) && !solo ? "-si" : "";
  const enName = solo ? "Sejong" : `${e}${e.includes("(") ? "" : suffix}, ${pe}`;
  return {
    id: `kr-${pi}-${i}`, name_ko: solo ? "세종" : `${pk} ${k}`, name_en: enName, lat, lon, tz: "Asia/Seoul", country: "KR",
    prov_ko: pk, prov_en: pe, short_ko: k,
  };
}));

const norm = (s) => String(s || "").toLowerCase().replace(/[\s\-,()]/g, "");
/** 이름 검색 (시도·시군구 일부, 영문 포함). 결과 최대 limit */
export function searchRegions(q, limit = 20) {
  const n = norm(q);
  if (!n) return [];
  const scored = [];
  for (const r of REGIONS_KR) {
    const ko = norm(r.name_ko), en = norm(r.name_en), sk = norm(r.short_ko), skBare = sk.replace(/(시|군|구)$/, "");
    let s = -1;
    if (sk === n || skBare === n) s = 0;
    else if (ko === n) s = 0;
    else if (sk.startsWith(n) || skBare.startsWith(n)) s = 1;
    else if (ko.includes(n)) s = 2;
    else if (en.startsWith(n)) s = 1;
    else if (en.includes(n)) s = 3;
    if (s >= 0) scored.push([s, r]);
  }
  return scored.sort((a, b) => a[0] - b[0]).slice(0, limit).map((x) => x[1]);
}
